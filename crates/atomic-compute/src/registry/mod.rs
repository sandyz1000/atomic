//! Compile-time dispatch registries — one module per subsystem.
//!
//! Every registry here follows the same shape: a `#[proc_macro]` in
//! `atomic-runtime-macros` (`register_shuffle_map!`, `register_state_merge!`, ...)
//! submits an entry via `inventory::submit!` at binary load; the corresponding
//! `Lazy<HashMap<&str, &'static Entry>>` here collects all submitted entries once, the
//! first time it's read — `inventory::iter` already hands out `&'static` references, so
//! the map borrows them directly rather than copying anything out. Each entry type owns
//! its dispatch behavior via a `call`/`build` method, so callers ask the entry to do its
//! job (`entry.call(..)`) rather than pulling a bare `fn` pointer out of it and calling
//! that separately. [`TASK_REGISTRY`] itself — the actual task registry — lives directly
//! in this file, and is the *only* registry for dispatch-by-name handlers: shuffle-map
//! handlers ([`shuffle`]) are `TaskEntry`s in it too, not a separate registry/ABI. [`shuffle`]
//! still owns the shuffle-map handler logic and the unrelated `SHUFFLE_KEY_REGISTRY`
//! (`TypeId` reflection, not dispatch); [`state_merge`] and [`partitioner`] each own one
//! other subsystem's registry end to end.

